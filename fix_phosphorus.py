async def fix():
    async with AsyncSessionLocal() as db:
        n = 0
        for name, p in CORRECTIONS:
            res = await db.execute(select(Feed).where(Feed.name == name))
            feed = res.scalar_one_or_none()
            if feed:
                feed.p_pct = p
                n += 1
            else:
                print(f"  ⚠ 未找到: {name}")
        await db.commit()
        print(f"✅ 已更新 {n} 条原料的磷值")

        # 复核
        print("\n复核（前几条）:")
        res = await db.execute(select(Feed).where(Feed.name.in_([
            "玉米", "豆粕（43%）", "磷酸氢钙", "尿素（缓释）", "过瘤胃赖氨酸（包被）"
        ])))
        for f in res.scalars().all():
            print(f"  {f.name:<22} p_pct={f.p_pct}")

asyncio.run(fix())